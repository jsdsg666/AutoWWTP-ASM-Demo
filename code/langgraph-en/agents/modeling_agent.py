# Parsing
# ---------------------------------------------------------------------------
def _parse_config_json(raw: str) -> dict | None:
    """Extract the 8-field JSON object from the LLM response. Return None on failure."""
    block = extract_json_block(raw)
    if block:
        try:
            return json.loads(block)
        except Exception:
            pass
    # Fallback: find the first complete JSON object.
    first = raw.find("{")
    if first < 0:
        return None
    depth = 0
    in_string = False
    escape_next = False
    for i in range(first, len(raw)):
        c = raw[i]
        if escape_next:
            escape_next = False
            continue
        if c == "\\" and in_string:
            escape_next = True
            continue
        if c == '"':
            in_string = not in_string
            continue
        if in_string:
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(raw[first:i + 1])
                except Exception:
                    return None
    return None


def _sanitize_config_shape(cfg: dict) -> dict:
    """Keep only the 8 top-level fields supported by run_pipeline and normalize boundaries."""
    cfg.pop("params", None)
    for k in EXTRA_TOP_LEVEL_KEYS:
        cfg.pop(k, None)

    cleaned = {k: cfg[k] for k in REQUIRED_KEYS if k in cfg}
    bnd = cleaned.get("boundaries")
    if not isinstance(bnd, dict):
        cleaned["boundaries"] = {k: None for k in BOUNDARY_KEYS}
        return cleaned

    cleaned["boundaries"] = {
        k: (bnd.get(k) if isinstance(bnd.get(k), dict) else None)
        for k in BOUNDARY_KEYS
    }
    return cleaned
